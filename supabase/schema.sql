create table if not exists public.properties (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(title) between 1 and 100),
    type text not null check (type in ('Villa', 'Appartement', 'Chambre salon', 'Cité')),
    location text not null check (char_length(location) between 1 and 200),
    price integer not null check (price > 0),
    image text not null,
    contact text not null check (char_length(contact) between 1 and 40),
    created_by uuid default auth.uid() references auth.users (id) on delete set null,
    created_at timestamptz not null default now()
);

alter table public.properties enable row level security;

drop policy if exists "Anyone can view properties" on public.properties;
create policy "Anyone can view properties"
    on public.properties for select
    using (true);

drop policy if exists "Authenticated users can publish properties" on public.properties;
create policy "Authenticated users can publish properties"
    on public.properties for insert
    to authenticated
    with check (auth.uid() = created_by);

drop policy if exists "Owners can update properties" on public.properties;
create policy "Owners can update properties"
    on public.properties for update
    to authenticated
    using (auth.uid() = created_by)
    with check (auth.uid() = created_by);

drop policy if exists "Admins can delete properties" on public.properties;
drop policy if exists "Owners and admins can delete properties" on public.properties;
create policy "Owners and admins can delete properties"
    on public.properties for delete
    to authenticated
    using (
        auth.uid() = created_by
        or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    );

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('property-images', 'property-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can view property images" on storage.objects;
create policy "Anyone can view property images"
    on storage.objects for select
    using (bucket_id = 'property-images');

drop policy if exists "Users can upload their own property images" on storage.objects;
create policy "Users can upload their own property images"
    on storage.objects for insert
    to authenticated
    with check (
        bucket_id = 'property-images'
        and (storage.foldername(name))[1] = auth.uid()::text
    );

drop policy if exists "Admins can delete property images" on storage.objects;
drop policy if exists "Owners and admins can delete property images" on storage.objects;
create policy "Owners and admins can delete property images"
    on storage.objects for delete
    to authenticated
    using (
        bucket_id = 'property-images'
        and (
            (storage.foldername(name))[1] = auth.uid()::text
            or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
        )
    );
